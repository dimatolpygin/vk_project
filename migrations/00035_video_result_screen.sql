-- Экран результата видео переехал с файла на кадр-превью.
--
-- Причина в ограничениях ВК: настоящее видео-вложение с плеером даёт только
-- video.save, а он недоступен токену сообщества («invalid token type»);
-- mp4-документ же приходит без обложки и выглядит безымянным файлом. Поэтому
-- в сообщении теперь кадр, с которого начиналась анимация, а сам ролик
-- открывается кнопкой «Скачать видео».
--
-- Текст экрана правится из админки, но заказчик его ещё не трогал: строка
-- заведена дефолтом на релизе этапа 10 час назад. Правим только текст, ровно
-- совпадающий с прежним дефолтом, — если админ уже переписал экран под себя,
-- миграция его не тронет.

UPDATE messages
SET text = '🎬 Готово! Видео на {{.Duration}} секунд.' || chr(10) || chr(10) ||
           'На картинке — кадр из него, сам ролик открывается по кнопке:',
    updated_at = now()
WHERE key = 'after_gen_video'
  AND text = '🎬 Готово! Твоё видео на {{.Duration}} секунд:';

